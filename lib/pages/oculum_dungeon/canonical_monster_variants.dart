MonsterBookEntry _canonicalCreature(
  String id,
  String name,
  String parent,
  List<String> planes,
  String element,
  List<int> stats,
  int level,
  String description,
  String weak,
  List<String> skills,
  String material, {
  bool peaceful = false,
  Map<String, String> resistances = const {},
}) =>
    _authoredPlanar(
      id,
      name,
      planes,
      element,
      description,
      weak,
      stats,
      level,
      false,
      false,
      skills,
      {
        'authoredCanonical': true,
        if (parent.isNotEmpty) 'canonicalVariantOf': parent,
        'dispositions': peaceful ? ['pacifico', 'neutrale'] : ['ostile'],
      },
      resistances,
    ).copyWith(
      dropIds: [material],
      dropChances: {material: 50},
      classificationTags: planes.contains('postea')
          ? ['Costrutto', 'Robot']
          : ['Creatura planare'],
    );

