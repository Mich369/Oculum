          duration: kind == 'scudo' ? '0' : '1',
        ),
      ],
  ],
  minimums: [1, 2, 3],
  maximums: [1, 2, 3],
  cd: [2, 3, 3],
  level: requiredLevel,
  costResource: 'volonta',
);

