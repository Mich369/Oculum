int oculumThunderBotExplosionDamage(int currentHp, int damage) =>
    max(0, currentHp) + max(0, damage);

MonsterConcreteTechnique _canonicalAttack(
  String name,
  String action,
  String element,
  List<int> damage, {
  int requiredLevel = 0,
  bool bleeding = false,
  bool burning = false,
  bool chilled = false,
}) => _planarMove(
  name,
  action,
  element,
  'danno',
  [
    for (var f = 0; f < 3; f++)
      [
        MonsterTechniqueEffect(
          'danno',
          '${damage[f]}',
          mode: 'prossima_azione',
          duration: '',
        ),
        if (f > 0 && (bleeding || burning))
          MonsterTechniqueEffect(
            'stato',
            '1',
            target: bleeding ? 'sanguinante' : 'bruciatura',
            duration: '1',
            recipient: 'nemico',
          ),
        if (f > 0 && chilled)
          const MonsterTechniqueEffect(
            'stato',
            '1',
            target: 'rallentato',
            duration: '1',
            recipient: 'nemico',
          ),
      ],
  ],
  level: requiredLevel,
  costResource: 'volonta',
  minimums: [1, 2, 3],
  maximums: [1, 2, 3],
  cd: [2, 2, 3],
);

MonsterConcreteTechnique _canonicalProtection(
  String name,
