MonsterConcreteTechnique _suggestedCycleMove(
  String id,
  String name,
  String description,
  String element,
  String kind,
  List<int> values, {
  String target = '',
  String recipient = 'se_stesso',
  List<int> cd = const [3, 3, 4],
}) {
  final owner = _suggestedCycleSpecs.firstWhere((s) => s.skills.contains(id));
  return _planarMove(
    name,
    description,
    element,
    kind,
    [
      for (final value in values)
        [
          MonsterTechniqueEffect(
            kind,
            '$value',
            target: target,
            mode: kind == 'danno'
                ? 'prossima_azione'
                : kind == 'planar' ||
                      kind == 'scudo' ||
                      kind == 'cura' ||
                      kind == 'costrutto'
                ? 'immediato'
                : 'temporaneo',
            duration: kind == 'danno' ? '' : '1',
            recipient: recipient,
          ),
        ],
    ],
    level: owner.level,
    minimums: const [1, 2, 3],
    maximums: const [1, 2, 3],
    cd: cd,
  );
}

