List<Map<String, dynamic>> _suggestedCycleAnatomy(String id) {
  final noBody = id == 'ciclo_melma_null';
  final quadruped = {
    'ciclo_riccio_pacifico',
    'ciclo_forest_demon_blu',
    'ciclo_cinghiale_fango',
    'ciclo_lupo_lunare',
    'ciclo_orso_aculei',
  }.contains(id);
  return [
    {'id': 'body', 'label': 'Corpo', 'group': 'body'},
    if (!noBody) ...[
      {'id': 'head', 'label': 'Testa', 'group': 'head'},
      {'id': 'torso', 'label': 'Torace', 'group': 'torso'},
      for (final group in quadruped ? ['legs'] : ['arms', 'legs'])
        for (var i = 0; i < (quadruped ? 4 : 2); i++)
          {
            'id': '${group}_${i + 1}',
            'label':
                '${group == 'arms'
                    ? 'Braccio'
                    : quadruped
                    ? 'Zampa'
                    : 'Gamba'} ${i.isEven ? 'destra' : 'sinistra'}${quadruped ? ' ${i ~/ 2 + 1}' : ''}',
            'group': group,
            'side': i.isEven ? 'right' : 'left',
            'sideIndex': i ~/ 2 + 1,
          },
      if (quadruped && id != 'ciclo_riccio_pacifico')
        {'id': 'tail', 'label': 'Coda', 'group': 'tail'},
    ],
    if (id == 'ciclo_solare_siccita')
      for (var i = 0; i < 2; i++)
        {
          'id': 'wings_${i + 1}',
          'label': 'Ala ${i == 0 ? 'destra' : 'sinistra'}',
          'group': 'wings',
          'side': i == 0 ? 'right' : 'left',
          'sideIndex': 1,
        },
    {
      'id': 'cycle_weak_point',
      'label': _suggestedCycleSpecs.firstWhere((s) => s.id == id).weak,
      'group': 'special',
      'weak': true,
    },
  ];
}

MonsterBookEntry _suggestedCycleEntry(_SuggestedCycleSpec s) =>
    _canonicalCreature(
      s.id,
      s.name,
      '',
      s.habitats,
      s.element,
      s.stats,
      s.level,
      s.description,
      s.weak,
      s.skills,
      s.material,
      peaceful: s.peaceful,
    ).copyWith(
      isNullFateless: s.phase == 'the_null',
      classificationTags: [
        if (s.phase.isNotEmpty) ...[
          'Creatura del ciclo',
          'Fase: ${oculumCycleMonsterPhaseNames[s.phase]}',
        ] else
          'Gigante',
        if (s.id == 'ciclo_gigante_goblin') 'Goblin',
        if (s.id == 'gigante_scheletro') 'Non morto',
      ],
      encounterRules: {
        'authoredCanonical': true,
        'cyclePhase': s.phase,
        'cycleScrollNaturalMinimum': 18,
        'cycleOpenName': s.open,
        'cycleOpenKind': s.peaceful ? 'cura' : 'danno',
        'dispositions': s.peaceful ? ['pacifico', 'neutrale'] : ['ostile'],
        'precisionBodyParts': _suggestedCycleAnatomy(s.id),
        if (s.id == 'ciclo_solare_siccita') ...{
          'celestialAllegiance': 'solare',
          'cycleLunarDamagePercent': 50,
          'naturalFlight': true,
        },
        if (s.id == 'ciclo_lupo_lunare') 'celestialAllegiance': 'lunare',
        if (s.id == 'ciclo_marmocchi_fato') ...{
          'fateGiftDoubleChance': 25,
          'fateGiftMaximumDonors': 3,
        },
      },
    );
