MonsterConcreteTechnique _octoberMove(
  String name,
  String action,
  String target,
  List<int> values, {
  String element = 'spirituale',
  String kind = 'controllo',
  String resource = 'oculum',
  List<int> costs = const [1, 2, 3],
  String recipient = 'se_stesso',
  List<int> cooldowns = const [2, 3, 4],
}) => MonsterConcreteTechnique(
  name: name,
  action: action,
  element: element,
  kind: kind,
  requiredLevel: 0,
  costResource: resource,
  minimums: costs,
  maximums: costs,
  cooldownValues: cooldowns,
  forms: [
    for (final value in values)
      [
        if (const {
          'wrong_bandit_combo',
          'redcap_poison',
          'strange_presence_push',
          'malicious_shaman_aphonia',
          'malicious_shaman_drain',
          'minor_malicious_shaman_aphonia',
          'minor_malicious_shaman_drain',
        }.contains(target)) ...[
          MonsterTechniqueEffect(
            'danno',
            '${value * 4}',
            mode: 'prossima_azione',
          ),
          if (target != 'wrong_bandit_combo')
            MonsterTechniqueEffect(
              'planar',
              '$value',
              target: target,
              recipient: 'nemico',
              duration: target.contains('malicious_shaman') ? '0' : '3',
            ),
        ] else
          MonsterTechniqueEffect(
            'planar',
            '$value',
            target: target,
            recipient: recipient,
          ),
      ],
  ],
);

