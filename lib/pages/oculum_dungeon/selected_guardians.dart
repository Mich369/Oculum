MonsterConcreteTechnique _guardianStrike(
  String name,
  String description,
  String element,
  String resource,
  List<int> damage,
) => _planarMove(
  name,
  description,
  element,
  'danno',
  [
    for (final value in damage)
      [
        MonsterTechniqueEffect(
          'danno',
          '$value',
          mode: 'prossima_azione',
          duration: '',
          maximumTargets: 1,
        ),
      ],
  ],
  level: 5,
  costResource: resource,
  minimums: [2, 3, 4],
  maximums: [2, 3, 4],
  cd: [2, 3, 3],
);

MonsterConcreteTechnique _guardianUtility(
  String name,
  String description,
  String element,
  String resource,
  String kind,
  MonsterTechniqueEffect Function(int) effect,
  List<int> values,
) => _planarMove(
  name,
  description,
  element,
  kind,
  [
    for (final value in values) [effect(value)],
  ],
  level: 5,
  costResource: resource,
  minimums: [2, 3, 4],
  maximums: [2, 3, 4],
  cd: [3, 3, 4],
);

